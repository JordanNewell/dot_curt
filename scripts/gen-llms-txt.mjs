// Generates site/llms-full.txt — the readable text of every main-site page,
// concatenated, per the llmstxt.org convention (llms.txt is hand-written;
// this file is derived). Zero-build friendly: plain node, no dependencies.
//
// Run: node scripts/gen-llms-txt.mjs   (from the repository root)

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SITE = join(ROOT, 'site');

const PAGES = [
	['index.html', 'Home — the format at a glance'],
	['adopt/index.html', 'Adopt — make your app speak .curt'],
	['try/index.html', 'Try — convert a ChatGPT or Claude export in the browser'],
	['viewer/index.html', 'Viewer — open a .curt file in the browser'],
	['extension/index.html', 'Curt Conversation Exporter — the browser extension'],
	['posts/2026-10-25-one-file/index.html', 'Launch post — one file, one conversation, kept whole'],
	['paper/index.html', 'The preprint — full text'],
	['listen/index.html', 'The listening copy — the paper read aloud (script)'],
];

function htmlToText(html) {
	let s = html
		.replace(/<script[\s\S]*?<\/script>/gi, '')
		.replace(/<style[\s\S]*?<\/style>/gi, '')
		.replace(/<svg[\s\S]*?<\/svg>/gi, '')
		.replace(/<head[\s\S]*?<\/head>/gi, '')
		.replace(/<(h[1-6]|p|li|tr|figcaption|pre|div|section|table)[\s>]/gi, '\n<$1');
	s = s
		.replace(/<li[^>]*>/gi, '- ')
		.replace(/<\/(h[1-6]|p|div|section|li|tr|pre|figcaption|table)>/gi, '\n')
		.replace(/<br\s*\/?>/gi, '\n')
		.replace(/<tspan[^>]*>/gi, ' ')
		.replace(/<\/tspan>/gi, '')
		.replace(/<[^>]+>/g, '');
	s = s
		.replace(/&amp;/g, '&')
		.replace(/&lt;/g, '<')
		.replace(/&gt;/g, '>')
		.replace(/&quot;/g, '"')
		.replace(/&#39;/g, "'")
		.replace(/&nbsp;/g, ' ');
	// collapse whitespace runs (but keep newlines) and blank-line runs
	s = s
		.split('\n')
		.map((l) => l.replace(/[ \t]+/g, ' ').trim())
		.join('\n')
		.replace(/\n{3,}/g, '\n\n')
		.trim();
	return s;
}

const out = [
	'# .curt — the open file format for AI conversations',
	'',
	'> Full-text companion to https://dotcurt.org/llms.txt — the readable',
	'> content of every main-site page, concatenated in reading order.',
	'> Generated by scripts/gen-llms-txt.mjs; regenerate after page edits.',
	'',
];

for (const [file, label] of PAGES) {
	const url = file === 'index.html'
		? 'https://dotcurt.org/'
		: 'https://dotcurt.org/' + file.replace(/\/?index\.html$/, '') + '/';
	const html = readFileSync(join(SITE, file), 'utf8');
	const title = (html.match(/<title>(.*?)<\/title>/s) ?? [])[1]?.trim() ?? label;
	out.push('---', '', `## ${label}`, `Source: ${url}`, '', htmlToText(html), '');
}

writeFileSync(join(SITE, 'llms-full.txt'), out.join('\n') + '\n');
console.log(`wrote site/llms-full.txt (${out.join('\n').length} bytes)`);
